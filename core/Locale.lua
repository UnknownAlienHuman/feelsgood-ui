local active = localeByCode[localeCode] or enUS
local cache = {}

local function L(key)
    if type(key) ~= "string" then
        return key
    end
    local cached = cache[key]
    if cached ~= nil then
        return cached
    end
    local value = active[key] or enUS[key] or key
    cache[key] = value
    return value
end

ns.L = L
ns.Locale = {
    code = localeCode,
    supported = localeByCode,
}
